import React, { useEffect, useRef, useState } from 'react';
import { Alert, Keyboard, Pressable, ScrollView, StyleSheet, Text, TextInput, View } from 'react-native';
import { Feather } from '@expo/vector-icons';
import * as SecureStore from 'expo-secure-store';

type Agent='opencode'|'codex'|'claude';
const names:Record<Agent,string>={opencode:'OpenCode',codex:'Codex',claude:'Claude Code'};
const STORAGE_URL='noethara-terminal-gateway-url';
const STORAGE_SECRET='noethara-terminal-gateway-token';
const COLORS={dark:'#171619',panel:'#252327',light:'#F2EDF5',muted:'#ACA7AD',violet:'#BBA5F8',line:'#413D45'};
type RuntimePacket={type?:string;data?:string;message?:string;agent?:string};
export function RemoteTerminal({agent,onBack}:{
  agent:Agent;onBack:()=>void;
}) {
  const selected=agent;
  const [url,setUrl]=useState('');
  const [secret,setSecret]=useState('');
  const [input,setInput]=useState('');
  const [output,setOutput]=useState('Noethara CLI\n');
  const [status,setStatus]=useState<'disconnected'|'connecting'|'connected'>('disconnected');
  const [setup,setSetup]=useState(false);
  const socket=useRef<WebSocket|null>(null);
  const scroller=useRef<ScrollView>(null);
  useEffect(()=>{
    let active=true;
    void Promise.all([SecureStore.getItemAsync(STORAGE_URL),SecureStore.getItemAsync(STORAGE_SECRET)])
      .then(([u,t])=>{if(active){setUrl(u||'');setSecret(t||'');}})
      .catch(()=>{});
    return()=>{active=false;socket.current?.close();socket.current=null;};
  },[]);
  const add=(text:string)=>setOutput(old=>(old+text).slice(-35000));
  const disconnect=()=>{socket.current?.close();socket.current=null;setStatus('disconnected');};
  const connect=async(target=selected)=>{
    if(socket.current)disconnect();
    const address=url.trim();
    if(!address.startsWith('wss://')&&!address.startsWith('ws://127.0.0.1')) {
      Alert.alert('Secure terminal required','Enter a wss:// gateway URL. Unencrypted public terminal connections are blocked.');
      setSetup(true);return;
    }
    if(!secret.trim()){
      Alert.alert('Runtime token missing','Enter the token generated by your private Linux terminal bridge.');
      setSetup(true);return;
    }
    await SecureStore.setItemAsync(STORAGE_URL,address);
    await SecureStore.setItemAsync(STORAGE_SECRET,secret);
    setSetup(false);setStatus('connecting');
    setOutput('Connecting to private '+names[target]+' runtime…\n');
    const ws=new WebSocket(address);
    socket.current=ws;
    ws.onopen=()=>{
      ws.send(JSON.stringify({type:'auth',token:secret,agent:target}));
    };
    ws.onmessage=(event)=>{
      try {
        const message=JSON.parse(String(event.data)) as RuntimePacket;
        if(message.type==='ready'){setStatus('connected');add('\n'+names[target]+' terminal ready.\n');}
        else if(message.type==='output')add(message.data||'');
        else if(message.type==='error'){add('\n'+(message.message||'Terminal error')+'\n');disconnect();}
        else if(message.type==='exit'){add('\nSession ended.\n');disconnect();}
      }catch{add(String(event.data));}
    };
    ws.onerror=()=>{add('\nConnection failed. Check the private runtime URL and TLS settings.\n');setStatus('disconnected');};
    ws.onclose=()=>{if(socket.current===ws)socket.current=null;setStatus('disconnected');};
  };
  const send=()=>{
    if(!input)return;
    if(status!=='connected'||socket.current?.readyState!==WebSocket.OPEN){
      add('\nNot connected. Attach your private Linux workspace first.\n');
      return;
    }
    socket.current.send(JSON.stringify({type:'input',data:input+'\r'}));
    setInput('');
  };
  const control=(type:'ctrl-c'|'tab'|'up'|'down')=>{
    if(status!=='connected'||socket.current?.readyState!==WebSocket.OPEN)return;
    const data=type==='ctrl-c'?'\x03':type==='tab'?'\t':type==='up'?'\x1b[A':'\x1b[B';
    socket.current.send(JSON.stringify({type:'input',data}));
  };
  return <View style={styles.root}>
    <View style={styles.top}>
      <Pressable style={styles.back} onPress={onBack}><Feather name="chevron-left" size={23} color={COLORS.light}/></Pressable>
      <View style={{flex:1}}><Text style={styles.head}>{names[selected]}</Text><Text style={styles.sub}>Private Linux workspace</Text></View>
      <View style={[styles.dot,{backgroundColor:status==='connected'?'#42D185':'#B8AFB9'}]}/>
      <Pressable onPress={()=>setSetup(v=>!v)} style={styles.back}><Feather name="settings" size={20} color={COLORS.light}/></Pressable>
    </View>
    <View style={styles.sessionBanner}>
      <View style={styles.sessionLogo}><Feather name="terminal" size={19} color="#BFA9EF"/></View>
      <View style={{flex:1}}>
        <Text style={styles.sessionTitle}>{names[selected]}</Text>
        <Text style={styles.sessionSubtitle}>Independent CLI session · {status}</Text>
      </View>
      <Pressable onPress={()=>{if(status==='connected')disconnect();else void connect();}}
        style={styles.sessionAction}>
        <Text style={styles.sessionActionText}>{status==='connected'?'Disconnect':'Connect'}</Text>
      </Pressable>
    </View>
    {setup&&<View style={styles.setup}>
      <Text style={styles.setupTitle}>Private workspace connection</Text>
      <TextInput style={styles.setupInput} value={url} onChangeText={setUrl} autoCapitalize="none"
        autoCorrect={false} placeholder="wss://your-private-bridge.example" placeholderTextColor="#8F8793"/>
      <TextInput style={styles.setupInput} value={secret} onChangeText={setSecret}
        secureTextEntry autoCapitalize="none" autoCorrect={false} placeholder="Runtime access token" placeholderTextColor="#8F8793"/>
      <Text style={styles.explain}>The Linux bridge must be running OpenCode, Codex or Claude Code. This app cannot execute CLI processes on your iPhone itself.</Text>
      <Pressable onPress={()=>void connect()} style={styles.connect}><Text style={styles.connectText}>Connect securely</Text></Pressable>
    </View>}
    <ScrollView style={styles.output} ref={scroller} onContentSizeChange={()=>scroller.current?.scrollToEnd({animated:true})}
      contentContainerStyle={{padding:17,flexGrow:1}} keyboardShouldPersistTaps="handled">
      <Text selectable style={styles.terminalText}>{output}</Text>
      {status==='disconnected'&&<View style={styles.welcome}>
        <Feather name="terminal" size={32} color={COLORS.violet}/>
        <Text style={styles.welcomeTitle}>{names[selected]} CLI</Text>
        <Text style={styles.welcomeDescription}>A separate Linux runtime is required for a real terminal. Connect your private workspace to start {names[selected]}. This is not the AI chat.</Text>
        <Pressable onPress={()=>setSetup(true)} style={styles.start}><Text style={styles.startLabel}>Configure connection</Text><Feather name="arrow-right" size={16} color="#FFFFFF"/></Pressable>
      </View>}
    </ScrollView>
    <View style={styles.shortcuts}>
      {([
        {label:'ESC',value:'ctrl-c' as const},{label:'TAB',value:'tab' as const},
        {label:'↑',value:'up' as const},{label:'↓',value:'down' as const},
      ]).map(item=><Pressable onPress={()=>control(item.value)} key={item.label} style={styles.shortcut}>
        <Text style={styles.shortcutText}>{item.label}</Text>
      </Pressable>)}
      <Text style={styles.connectionLabel}>{status}</Text>
    </View>
    <View style={styles.composer}>
      <TextInput value={input} onChangeText={setInput} onSubmitEditing={send} autoCapitalize="none" autoCorrect={false}
        placeholder="Terminal input…" placeholderTextColor="#8E8691" style={styles.input}/>
      <Pressable onPress={send} style={styles.send}><Feather name="corner-down-left" size={21} color="#FFFFFF"/></Pressable>
    </View>
  </View>;
}
const styles=StyleSheet.create({
  root:{flex:1,backgroundColor:COLORS.dark},top:{height:68,flexDirection:'row',alignItems:'center',paddingHorizontal:14,gap:11},
  back:{padding:9},head:{color:COLORS.light,fontWeight:'700',fontSize:19},
  sub:{color:COLORS.muted,fontSize:11,marginTop:4},
  dot:{width:9,height:9,borderRadius:7},
  sessionBanner:{marginHorizontal:15,marginBottom:14,backgroundColor:'#222127',borderColor:'#363039',
    borderWidth:1,borderRadius:16,padding:13,flexDirection:'row',alignItems:'center',gap:12},
  sessionLogo:{width:41,height:41,borderRadius:13,backgroundColor:'#32293E',justifyContent:'center',alignItems:'center'},
  sessionTitle:{fontSize:15,fontWeight:'700',color:COLORS.light},
  sessionSubtitle:{fontSize:11,color:'#958E9B',marginTop:5},
  sessionAction:{backgroundColor:'#372D42',borderRadius:11,paddingVertical:10,paddingHorizontal:12},
  sessionActionText:{color:'#D3BFF2',fontSize:11,fontWeight:'700'},
  setup:{marginHorizontal:15,backgroundColor:COLORS.panel,borderRadius:15,padding:15,gap:10,marginBottom:12},
  setupTitle:{color:COLORS.light,fontSize:14,fontWeight:'700'},
  setupInput:{backgroundColor:'#1A191C',borderWidth:1,borderColor:COLORS.line,borderRadius:10,
    fontSize:13,color:COLORS.light,padding:11},
  explain:{fontSize:11.5,lineHeight:18,color:COLORS.muted},
  connect:{alignItems:'center',borderRadius:11,backgroundColor:'#7B60C3',paddingVertical:11},
  connectText:{color:'#FFFFFF',fontWeight:'700',fontSize:13},
  output:{flex:1,backgroundColor:'#111013',marginHorizontal:15,borderRadius:14,borderWidth:1,borderColor:'#2F2B32'},
  terminalText:{fontFamily:'monospace',fontSize:12.5,lineHeight:20,color:'#D6D4DC'},
  welcome:{marginTop:26,alignItems:'flex-start',paddingHorizontal:7},
  welcomeTitle:{color:COLORS.light,fontWeight:'700',fontSize:19,marginTop:16},
  welcomeDescription:{color:COLORS.muted,fontSize:13,lineHeight:21,marginTop:11},
  start:{flexDirection:'row',gap:11,alignItems:'center',marginTop:19,paddingVertical:12,paddingHorizontal:16,
    backgroundColor:'#7B60C3',borderRadius:12},
  startLabel:{color:'#FFFFFF',fontSize:13,fontWeight:'600'},
  shortcuts:{flexDirection:'row',alignItems:'center',gap:8,paddingHorizontal:16,paddingVertical:11},
  shortcut:{paddingHorizontal:14,paddingVertical:9,borderRadius:9,backgroundColor:'#2B2930'},
  shortcutText:{color:'#E1DCE6',fontWeight:'600',fontSize:12},
  connectionLabel:{color:COLORS.muted,fontSize:10,marginLeft:'auto'},
  composer:{flexDirection:'row',gap:10,paddingHorizontal:15,paddingBottom:12},
  input:{flex:1,color:'#EDE9F3',backgroundColor:'#29262D',borderRadius:12,padding:12,fontFamily:'monospace',fontSize:13},
  send:{backgroundColor:'#7B60C3',borderRadius:11,width:48,alignItems:'center',justifyContent:'center'}
});
